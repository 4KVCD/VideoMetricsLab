"""Compiles native/vulkan_presenter.slang (the Vulkan presenter's vertex and
fragment shaders) to SPIR-V, into native/vulkan_presenter_spv.h, which is
committed: building vulkan_presenter.dll (scripts/build_vulkan_presenter.ps1)
then needs only g++. Run after changing the shaders:

    python scripts/build_vulkan_presenter_shader.py --slangc <path to slangc.exe>

Slang 2026.10.2 (https://github.com/shader-slang/slang/releases), the version
the committed header was made with.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "native" / "vulkan_presenter.slang"
OUTPUT = ROOT / "native" / "vulkan_presenter_spv.h"
#: The header's array name for each entry point and the stage it is for.
SHADERS = {"kVertexSpirv": ("vertex_main", "vertex"), "kFragmentSpirv": ("fragment_main", "fragment")}


def main() -> int:
    """Compiles the Vulkan presenter shader with slangc and writes it as a C header."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--slangc", required=True, type=Path)
    args = parser.parse_args()
    lines = ["// Generated by scripts/build_vulkan_presenter_shader.py from native/vulkan_presenter.slang:"
             " do not edit.", "#pragma once", "#include <stdint.h>", ""]
    with tempfile.TemporaryDirectory() as folder:
        for name, (entry, stage) in SHADERS.items():
            spirv = Path(folder) / f"{entry}.spv"
            subprocess.run([str(args.slangc), str(SOURCE), "-target", "spirv", "-profile", "spirv_1_3", "-entry",
                            entry, "-stage", stage, "-O2", "-o", str(spirv)], check=True)
            data = spirv.read_bytes()
            words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
            lines.append(f"static const uint32_t {name}[] = {{")
            lines += ["    " + ", ".join(f"0x{word:08x}" for word in words[i:i + 8]) + ","
                      for i in range(0, len(words), 8)]
            lines += ["};", ""]
    OUTPUT.write_text("\n".join(lines), encoding="ascii", newline="\n")
    print(f"{OUTPUT.relative_to(ROOT)}: {OUTPUT.stat().st_size} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
